  /// Lấy chuỗi bản dịch theo từ khóa và ngôn ngữ hiện tại
  static String tr(String key, {String? language, Map<String, String>? params}) {
    final lang = language ?? 'Tiếng Việt';
    final dict = _localizedValues[lang] ?? _localizedValues['Tiếng Việt']!;
    String text = dict[key] ?? _localizedValues['Tiếng Việt']?[key] ?? key;

    if (params != null) {
      params.forEach((paramKey, paramValue) {
        text = text.replaceAll('{$paramKey}', paramValue);
      });
    }

    return text;
  }
